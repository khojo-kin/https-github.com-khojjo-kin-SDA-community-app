-- Columns: number, title, section, author. The section is the hymnal's own topical heading
-- (the sub-heading printed above each hymn, e.g. "Adoration and Praise", "Second Advent",
-- "Sabbath"), so the app can group the index the way the printed book does.
--
-- Lyrics are deliberately left empty (''). Admins type them in from the app (Edit lyrics on a
-- hymn), and until then the hymn page shows the words from hymnary.org. Re-running this file is
-- safe: the ON CONFLICT clause refreshes title, section and author but NEVER touches lyrics, so
-- nothing an admin has typed is overwritten.
--
-- Titles and sections: hymnary.org/hymnal/SDAH1985 index, cross-checked against two public
-- hymnal datasets. Authors: hymnary.org author index where it could be read; a few remain
-- blank (spirituals, psalms, anonymous texts and a handful that could not be fetched) and can be
-- filled in by an admin.

